export const dict: Record<Lang, Dict> = { en, hi };

export function paramName(t: Dict, p: string): string {
  return t.param[p] ?? p;
}

/** Translate a series label like "Ganesh 2023 pre". */
export function seriesLabel(t: Dict, label: string): string {
  const [f, y, ph] = label.split(" ");
  return `${t.festival[f] ?? f} ${y} ${t.phase[ph as Phase] ?? ph ?? ""}`.trim();
}
